# B2B Sales & Transaction Analysis

Projekt analityczno-bazodanowy dla systemu B2B, zaprojektowany w celu modelowania danych transakcyjnych oraz generowania raportów finansowych przy użyciu SQL.

## Struktura projektu
- `schema.sql` – Definicja struktury bazy danych (tabele `contractors` i `transactions` powiązane kluczem obcym).
- `data.sql` – Przykładowe dane testowe (kontrahenci i faktury).
- `queries.sql` – Zapytania analityczne (agregacje, łączenie tabel `JOIN`, funkcje okna).

## Technologie
- SQL / SQLite
- VS Code